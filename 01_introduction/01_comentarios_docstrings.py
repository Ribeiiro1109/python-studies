"""
Python - Comentários e DocStrings

Comentários e DocStrings são utilizados para documentar o código
e facilitar sua compreensão.

Comentários:
- São escritos utilizando o símbolo #.
- Servem para explicar trechos específicos do código.
- São ignorados durante a execução do programa.

DocStrings:
- São escritas utilizando três aspas simples (' '') ou três aspas duplas (" "").
- São utilizadas para documentar módulos, funções, classes e métodos.
- Também podem ser usadas para escrever observações durante os estudos.
"""

# ==========================================================
# Exemplo 1 - Comentário de uma linha
# ==========================================================

# Este comentário serve apenas para explicar o código.
print(1234)  # Exibe o número 1234 no terminal.

print()

# ==========================================================
# Exemplo 2 - DocString utilizando aspas duplas
# ==========================================================

"""
Esta é uma DocString.

Ela pode conter várias linhas de texto e normalmente é utilizada
para documentar o código.
"""

print("Exemplo utilizando DocString com aspas duplas.")

print()

# ==========================================================
# Exemplo 3 - DocString utilizando aspas simples
# ==========================================================

'''
Também é possível criar uma DocString utilizando
três aspas simples.
'''

print("Exemplo utilizando DocString com aspas simples.")

print()

# ==========================================================
# Importante
# ==========================================================

# Comentários e DocStrings possuem finalidades diferentes.
#
# Comentários (#):
# - Explicam partes específicas do código.
#
# DocStrings:
# - Documentam módulos, funções, classes e métodos.
# - Podem ser acessadas por ferramentas de documentação
#   e pela função help().

# Durante os estudos é comum utilizar DocStrings como anotações,
# mas em projetos reais seu principal objetivo é documentar o código.